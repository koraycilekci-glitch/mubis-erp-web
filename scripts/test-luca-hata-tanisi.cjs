const fs = require('node:fs')
const vm = require('node:vm')
const assert = require('node:assert/strict')

const source = fs.readFileSync('gib-yardimci-sunucu/index.js', 'utf8')
const start = source.indexOf('function lucaAkisHataMesaji(error) {')
const end = source.indexOf('var sDurum =', start)
assert.ok(start >= 0 && end > start)
const classify = vm.runInNewContext(source.slice(start, end) + '\nlucaAkisHataMesaji')

assert.match(classify(new Error('Luca GIB sorgusunda yetki veya firma kimlik hatasi bildirdi.')), /yetki/)
assert.match(classify(new Error('Luca fatura listesi 30 saniye icinde dogrulanamadi;')), /liste/)
assert.match(classify(new Error('Luca fatura satırının belge tarihi okunamadı; indirme başlatılmadı.')), /tarih/)
assert.match(classify(new Error('Luca fatura sayfası veya sayfa geçişi 30 saniyede doğrulanamadı.')), /sayfaları/)
assert.match(classify({ code: 'LUCA_INVOICES_INCOMPLETE', message: '1 fatura doğrulanamadı: private-invoice' }), /arşiv/)
assert.doesNotMatch(classify({ code: 'LUCA_INVOICES_INCOMPLETE', message: 'private-invoice' }), /private-invoice/)
assert.match(classify(new Error('Luca GIB islem takibi suresinde tamamlanmadi')), /Durdur/)
assert.equal(classify(new Error('unrecognized private details')), '')
assert.ok(source.includes('yonHatasi = lucaAkisHataMesaji(e);'))
console.log('PASS: Luca errors classified without exposing invoice IDs or unrecognized details')

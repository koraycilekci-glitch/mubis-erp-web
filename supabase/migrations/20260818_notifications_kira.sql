create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  client_id bigint,
  user_id uuid,
  type text not null default 'general',
  title text not null,
  message text not null,
  route text,
  metadata jsonb not null default '{}'::jsonb,
  is_read boolean not null default false,
  okundu boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.notifications enable row level security;

create index if not exists notifications_created_at_idx
  on public.notifications (created_at desc);

create index if not exists notifications_is_read_idx
  on public.notifications (is_read);

create index if not exists notifications_client_id_idx
  on public.notifications (client_id);

drop policy if exists notifications_authenticated_read on public.notifications;
create policy notifications_authenticated_read
  on public.notifications for select
  to authenticated
  using (true);

drop policy if exists notifications_authenticated_update on public.notifications;
create policy notifications_authenticated_update
  on public.notifications for update
  to authenticated
  using (true)
  with check (true);

drop policy if exists notifications_authenticated_insert on public.notifications;
create policy notifications_authenticated_insert
  on public.notifications for insert
  to authenticated
  with check (true);

alter table public.notifications replica identity full;